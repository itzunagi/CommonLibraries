using Common.SimpleSourceMapper.Tests.Fixtures;
using Xunit;

namespace Common.SimpleSourceMapper.Tests.GeneratorTests;

public class GeneratedCodeTests
{
    [Fact]
    public void Generated_source_matches_the_expected_text()
    {
        var result = Harness.Run("""
            using Common.SimpleSourceMapper;
            using Domain;
            namespace Example
            {
                public static partial class CustomerMappings
                {
                    [Map(MemberList.Both)]
                    [ForMember(nameof(CustomerDto.DisplayName), nameof(Customer.Name))]
                    public static partial CustomerDto ToDto(Customer source);
                }
            }
            """);

        result.AssertGenerated(1);
        const string expected = """
            // <auto-generated>
            //     Generated by Common.SimpleSourceMapper.Compiler. Changes will be lost when the file is regenerated.
            // </auto-generated>
            #nullable enable

            namespace Example
            {
                partial class CustomerMappings
                {
                    public static partial global::Domain.CustomerDto ToDto(global::Domain.Customer source)
                    {
                        if (source is null)
                        {
                            throw new global::System.ArgumentNullException(nameof(source));
                        }

                        return new global::Domain.CustomerDto
                        {
                            DisplayName = source.Name,
                            Id = source.Id,
                        };
                    }
                }
            }

            """;
        Assert.Equal(expected.Replace("\r\n", "\n"), result.Generated[0].Text);
    }

    [Fact]
    public void Generation_is_deterministic()
    {
        var sources = new[]
        {
            Harness.InMapper("[Map(MemberList.Both)] public static partial Dst ToDst(Src source); [Map(MemberList.Both)] public static partial Src ToSrc(Dst source);")
        };

        var first = Harness.Run(sources);
        var second = Harness.Run(sources);
        Assert.Equal(first.Generated, second.Generated);
    }

    [Fact]
    public void Header_and_nullable_directive_are_present_in_every_file()
    {
        var result = Harness.Run(Harness.InMapper("[Map(MemberList.Both)] public static partial Dst ToDst(Src source);"));
        foreach (var (_, text) in result.Generated)
        {
            Assert.StartsWith("// <auto-generated>", text);
            Assert.Contains("#nullable enable", text);
        }
    }

    [Fact]
    public void Mapping_attributes_are_not_copied_onto_the_implementation()
    {
        var result = Harness.Run(Harness.InMapper("[Map(MemberList.Both)] public static partial Dst ToDst(Src source);"));
        Assert.DoesNotContain("[", result.GeneratedText);
    }

    [Fact]
    public void Overloads_with_the_same_name_get_distinct_hint_names()
    {
        var result = Harness.Run(Harness.InMapper(
            "[Map(MemberList.Both)] public static partial Dst ToDst(Src source); [Map(MemberList.Both)] public static partial Src ToDst(Dst source);"));
        result.AssertGenerated(2);
        Assert.Equal(2, result.Generated.Select(g => g.HintName).Distinct().Count());
    }

    [Fact]
    public void Hint_names_that_sanitize_identically_do_not_collide()
    {
        var result = Harness.Run(
            Harness.InMapper("[Map(MemberList.Both)] public static partial Dst ToDst(Src source);", className: "Outer_Inner"),
            """
            using Common.SimpleSourceMapper;
            using Domain;
            namespace T
            {
                public static partial class Outer
                {
                    public static partial class Inner
                    {
                        [Map(MemberList.Both)] public static partial Src ToSrc(Dst source);
                    }
                }
            }
            """);
        result.AssertGenerated(2);
        Assert.Equal(2, result.Generated.Select(g => g.HintName).Distinct().Count());
    }

    [Fact]
    public void Escaped_identifiers_are_emitted_correctly()
    {
        var result = Harness.Run(Harness.InMapper(
            "[Map(MemberList.Both)] public static partial @event ToEvent(@class @object);",
            "public class @class { public int @namespace { get; set; } public string @string { get; set; } = \"\"; } public class @event { public int @namespace { get; set; } public string @string { get; set; } = \"\"; }",
            className: "@static_"));
        result.AssertGenerated(1);
        Assert.Contains("@namespace = @object.@namespace", result.GeneratedText);
    }

    [Fact]
    public void Keyword_named_namespace_and_container_are_escaped()
    {
        var result = Harness.Run("""
            using Common.SimpleSourceMapper;
            using Domain;
            namespace @internal.@event
            {
                public static partial class @lock
                {
                    [Map(MemberList.Both)] public static partial Dst ToDst(Src source);
                }
            }
            """);
        result.AssertGenerated(1);
    }

    [Fact]
    public void Invalid_mappings_never_emit_a_throwing_stub()
    {
        var result = Harness.Run(Harness.InMapper("[Map(MemberList.Both)] [ForMember(\"Nope\", \"Id\")] public static partial Dst ToDst(Src source);"));
        Assert.Empty(result.Generated);
        Assert.Contains("SSM006", result.Ids);
    }

    [Fact]
    public void Mapper_diagnostics_accompany_the_missing_implementation_error()
    {
        var result = Harness.Run(Harness.InMapper("[Map(MemberList.Both)] [ForMember(\"Nope\", \"Id\")] public static partial Dst ToDst(Src source);"));
        Assert.Contains(result.CompilationErrors, d => d.Id == "CS8795");
        Assert.Contains("SSM006", result.Ids);
        Assert.Empty(result.UnexpectedCompilationErrors());
    }

    [Fact]
    public void Diagnostics_carry_actionable_messages()
    {
        var result = Harness.Run(Harness.InMapper("[Map(MemberList.Both)] public static partial B ToB(A source);",
            "public class A { public int Id { get; set; } } public class B { public int Id { get; set; } public int Extra { get; set; } }"));
        var message = Assert.Single(result.All).GetMessage();
        Assert.Contains("ToB", message);
        Assert.Contains("Extra", message);
        Assert.Contains("A -> B", message);
        Assert.Contains("ForMember", message);
    }
}
