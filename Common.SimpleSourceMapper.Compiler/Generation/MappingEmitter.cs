using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Common.SimpleSourceMapper.Compiler.Models;

namespace Common.SimpleSourceMapper.Compiler.Generation;

internal static class MappingEmitter
{
    public static string Emit(ResolvedMapping mapping)
    {
        var model = mapping.Model;
        var writer = new IndentedWriter();

        writer.Line("// <auto-generated>");
        writer.Line("//     Generated by Common.SimpleSourceMapper.Compiler. Changes will be lost when the file is regenerated.");
        writer.Line("// </auto-generated>");
        writer.Line(model.NullableEnabled ? "#nullable enable" : "#nullable disable");
        writer.Line();

        var hasNamespace = model.Namespace.Length > 0;
        if (hasNamespace)
        {
            writer.Line($"namespace {model.Namespace}");
            writer.Open();
        }

        foreach (var container in model.Containers)
        {
            writer.Line($"partial class {container}");
            writer.Open();
        }

        writer.Line($"public static partial {model.DestinationTypeAnnotated} {model.MethodName}({model.SourceTypeAnnotated} {model.ParameterName})");
        writer.Open();

        if (model.SourceIsReferenceType)
        {
            writer.Line($"if ({model.ParameterName} is null)");
            writer.Open();
            writer.Line($"throw new global::System.ArgumentNullException(nameof({model.ParameterName}));");
            writer.Close();
            writer.Line();
        }

        var locals = new Dictionary<string, string>(StringComparer.Ordinal);
        var prefix = "__ssm";
        while (model.ParameterName == prefix + "0")
        {
            prefix += "_";
        }

        // Nullable nested sources are read once so the getter is not evaluated repeatedly.
        foreach (var assignment in model.Assignments.Where(a => a.Kind == AssignmentKind.Nested && a.Guard))
        {
            var local = prefix + locals.Count;
            locals[assignment.DestinationProperty] = local;
            writer.Line($"var {local} = {model.ParameterName}.{assignment.SourceProperty};");
        }

        if (locals.Count > 0)
        {
            writer.Line();
        }

        if (model.Assignments.Count == 0)
        {
            writer.Line($"return new {model.DestinationType}();");
        }
        else
        {
            writer.Line($"return new {model.DestinationType}");
            writer.Open();
            foreach (var assignment in model.Assignments)
            {
                writer.Line($"{assignment.DestinationProperty} = {Expression(mapping, assignment, locals)},");
            }

            writer.Close(";");
        }

        writer.Close();

        foreach (var _ in model.Containers)
        {
            writer.Close();
        }

        if (hasNamespace)
        {
            writer.Close();
        }

        return writer.ToString();
    }

    private static string Expression(ResolvedMapping mapping, AssignmentModel assignment, Dictionary<string, string> locals)
    {
        var model = mapping.Model;
        var sourceAccess = $"{model.ParameterName}.{assignment.SourceProperty}";

        if (assignment.Kind == AssignmentKind.Direct)
        {
            return sourceAccess;
        }

        var target = mapping.Targets[assignment.DestinationProperty];
        if (!assignment.Guard)
        {
            return $"{target.CallName}({sourceAccess})";
        }

        var local = locals[assignment.DestinationProperty];
        return assignment.SourceIsNullableValue
            ? $"{local}.HasValue ? {target.CallName}({local}.Value) : default({assignment.DestinationType})"
            : $"{local} is null ? default({assignment.DestinationType}) : {target.CallName}({local})";
    }

    /// <summary>Stable, collision-resistant hint name: sanitized container and method plus a hash of the full signature.</summary>
    public static string HintName(MappingModel model)
    {
        var readable = new StringBuilder();
        foreach (var c in $"{model.ContainerFullName}.{model.MethodName}".Replace("global::", string.Empty))
        {
            readable.Append(char.IsLetterOrDigit(c) || c == '.' || c == '_' ? c : '_');
        }

        return $"{readable}.{Hash(model.MethodKey)}.g.cs";
    }

    private static string Hash(string text)
    {
        // FNV-1a keeps the name stable across runs and machines (string.GetHashCode is randomized).
        var hash = 2166136261u;
        foreach (var c in text)
        {
            hash = unchecked((hash ^ c) * 16777619u);
        }

        return hash.ToString("x8");
    }

    private sealed class IndentedWriter
    {
        private readonly StringBuilder _builder = new();
        private int _indent;

        public void Line(string text = "")
        {
            if (text.Length > 0)
            {
                _builder.Append(' ', _indent * 4);
                _builder.Append(text);
            }

            _builder.Append('\n');
        }

        public void Open()
        {
            Line("{");
            _indent++;
        }

        public void Close(string suffix = "")
        {
            _indent--;
            Line("}" + suffix);
        }

        public override string ToString() => _builder.ToString();
    }
}
